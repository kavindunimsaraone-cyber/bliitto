        <script>
            document.addEventListener('DOMContentLoaded', function() {
                const tabBtns = document.querySelectorAll('.about-tab-btn');
                const tabPanes = document.querySelectorAll('.about-tab-pane');

                function activateTab(tabId) {
                    tabBtns.forEach(b => b.classList.remove('active'));
                    tabPanes.forEach(p => p.classList.remove('active'));

                    const btn = document.querySelector(`.about-tab-btn[data-tab="${tabId}"]`);
                    const pane = document.getElementById(tabId);
                    
                    if (btn && pane) {
                        btn.classList.add('active');
                        pane.classList.add('active');
                    }
                }

                tabBtns.forEach(btn => {
                    btn.addEventListener('click', () => {
                        activateTab(btn.getAttribute('data-tab'));
                    });
                });

                // Handle hash in URL for dropdown menu links
                function handleHashChange() {
                    if (window.location.hash) {
                        const hash = window.location.hash.substring(1);
                        const hashToTab = {
                            'vision': 'tab-vision',
                            'staff': 'tab-staff',
                            'ip-committee': 'tab-ip',
                            'coordinating': 'tab-coordinating'
                        };
                        
                        if (hashToTab[hash]) {
                            activateTab(hashToTab[hash]);
                        }
                    }
                }
                
                handleHashChange();
                window.addEventListener('hashchange', handleHashChange);
            });
        </script>
